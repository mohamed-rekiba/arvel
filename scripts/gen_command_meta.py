"""Regenerate ``arvel/console/_command_meta.py`` from the live entry points.

The CLI renders ``arvel --help`` from this manifest so it doesn't import all
~73 command classes (which drag in FastAPI/SQLAlchemy/jinja2) just to show the
listing. Run after adding/renaming a command or editing its ``help``:

    uv run python scripts/gen_command_meta.py

The drift-guard test (tests/console/test_command_meta_drift.py) fails if this
file goes stale.
"""

from __future__ import annotations

import json
from pathlib import Path

from arvel.console._loader import discover_commands

_TARGET = Path(__file__).resolve().parents[1] / "packages/arvel/src/arvel/console/_command_meta.py"


def collect() -> dict[str, str]:
    """Map command name -> stripped help for every loadable arvel.commands entry point."""
    return dict(sorted((c.name, (c.help or "").strip()) for c in discover_commands()))


def render(data: dict[str, str]) -> str:
    header = (
        '"""Command name -> short help, used to render ``arvel --help`` without\n'
        "importing command implementations. Generated by scripts/gen_command_meta.py;\n"
        'a drift-guard test keeps it in sync. Do not edit by hand."""\n\n'
        "from __future__ import annotations\n\n"
        "COMMAND_HELP: dict[str, str] = {\n"
    )
    # json.dumps emits double-quoted, escaped literals that ruff format leaves alone,
    # so regenerating never re-triggers the formatter.
    body = "".join(
        f"    {json.dumps(name)}: {json.dumps(help_)},\n" for name, help_ in data.items()
    )
    return f"{header}{body}}}\n"


def main() -> None:
    _TARGET.write_text(render(collect()), encoding="utf-8")
    print(f"wrote {_TARGET} ({len(collect())} commands)")


if __name__ == "__main__":
    main()
